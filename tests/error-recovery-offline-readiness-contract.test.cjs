// Phase 8.14 — recovery/offline readiness contract assertions
'use strict';
const assert=require('node:assert/strict');
const c=require('../qa/error-recovery-offline-readiness-contract.cjs');
assert.equal(c.classifyError({code:'network_error'}).retryable,true);
assert.equal(c.classifyError({code:'timeout'}).retryable,true);
assert.equal(c.classifyError({code:'server_5xx'}).retryable,true);
assert.equal(c.classifyError({code:'validation_error'}).retryable,false);
assert.equal(c.classifyError({code:'payment_declined'}).retryable,false);
assert.equal(c.classifyError({code:'unknown'}).retryable,false);
assert.equal(c.recoveryDecision({code:'network_error',online:true,retryCount:0}).retry,true);
assert.equal(c.recoveryDecision({code:'network_error',online:false,retryCount:0}).reason,'offline_wait_for_reconnect');
assert.equal(c.recoveryDecision({code:'timeout',online:true,retryCount:3}).reason,'retry_limit');
assert.equal(c.recoveryDecision({code:'network_error',online:true,retryCount:1,duplicateRisk:true}).reason,'duplicate_risk_requires_reconciliation');
assert.equal(c.offlineReadiness({online:true,stale:false,authenticated:true}).ready,true);
assert.equal(c.offlineReadiness({online:false,authenticated:true}).reason,'offline');
assert.equal(c.offlineReadiness({online:true,stale:true,authenticated:true}).reason,'stale_data');
assert.equal(c.offlineReadiness({online:true,stale:false,authenticated:false}).reason,'auth_required');
assert.equal(c.checkReconnect({online:true,pendingMutation:false,sessionValid:true}).ok,true);
assert.equal(c.checkReconnect({online:false,pendingMutation:false,sessionValid:true}).reason,'still_offline');
assert.equal(c.checkReconnect({online:true,pendingMutation:true,sessionValid:true}).reason,'pending_mutation_needs_reconciliation');
assert.equal(c.checkReconnect({online:true,pendingMutation:false,sessionValid:false}).reason,'session_refresh_required');
assert.equal(c.validateRetry({idempotencyKey:'k',originalOperationId:'op1',retryOperationId:'op1',retryCount:1}).valid,true);
assert.equal(c.validateRetry({originalOperationId:'op1',retryOperationId:'op1',retryCount:1}).reason,'missing_idempotency_key');
assert.equal(c.validateRetry({idempotencyKey:'k',originalOperationId:'op1',retryOperationId:'op2',retryCount:1}).reason,'operation_id_mismatch');
assert.equal(c.validateRetry({idempotencyKey:'k',originalOperationId:'op1',retryOperationId:'op1',retryCount:4}).reason,'retry_limit');
assert.equal(c.fallbackPolicy('payment'),'never_retry_automatically');
assert.equal(c.fallbackPolicy('ride_booking'),'block_until_online_and_confirmed');
assert.equal(c.fallbackPolicy('unknown'),'safe_block_and_show_recovery');
console.log('Phase 8.14 recovery contract assertions authored (not executed).');
