// Phase 8.14 — Error recovery & failure handling assertions.
'use strict';
const assert=require('node:assert/strict');
const c=require('../qa/error-recovery-failure-handling-contract.cjs');
assert.equal(c.validRetryPolicy({maxAttempts:3,baseDelayMs:100,maxDelayMs:1000}),true);
assert.equal(c.validRetryPolicy({maxAttempts:8,baseDelayMs:100,maxDelayMs:1000}),false);
assert.equal(c.shouldRetry({attempt:1,maxAttempts:3,retryable:true}),true);
assert.equal(c.shouldRetry({attempt:3,maxAttempts:3,retryable:true}),false);
assert.equal(c.shouldRetry({attempt:1,maxAttempts:3,retryable:false}),false);
assert.equal(c.retryDelay({attempt:1,baseDelayMs:100,maxDelayMs:1000}),100);
assert.equal(c.retryDelay({attempt:4,baseDelayMs:100,maxDelayMs:500}),500);
assert.equal(c.retryDelay({attempt:0,baseDelayMs:100,maxDelayMs:500}),null);
assert.equal(c.classifyFailure({code:'TIMEOUT'}),'timeout');
assert.equal(c.classifyFailure({status:503}),'transient_network');
assert.equal(c.classifyFailure({status:403}),'auth_or_permission');
assert.equal(c.classifyFailure({status:409}),'conflict');
assert.equal(c.classifyFailure({status:422}),'client_error');
assert.equal(c.recoveryAction('timeout'),'retry_with_backoff');
assert.equal(c.recoveryAction('conflict'),'refresh_state_then_retry');
assert.equal(c.recoveryAction('auth_or_permission'),'reauthenticate_or_check_access');
assert.equal(c.recoveryAction('client_error'),'correct_request_no_retry');
assert.equal(c.checkPartialState({steps:['created','assigned','started','done'],completedSteps:['created','assigned'],failedStep:'started',compensatingAction:'reassign'}).safe,true);
assert.equal(c.checkPartialState({steps:['created','assigned','started'],completedSteps:['created'],failedStep:'assigned',compensatingAction:null}).reason,'compensation_required');
assert.equal(c.checkPartialState({steps:['created','assigned'],completedSteps:['created','unknown'],failedStep:'assigned'}).reason,'unknown_step');
assert.equal(c.checkResume({workflowId:'wf1',currentState:'assigned',expectedState:'assigned'}).allowed,true);
assert.equal(c.checkResume({workflowId:'wf1',currentState:'cancelled',expectedState:'assigned'}).reason,'state_mismatch');
assert.equal(c.checkResume({currentState:'assigned',expectedState:'assigned'}).reason,'missing_resume_context');
assert.equal(c.checkRecoveryRecord({workflow_id:'wf1',failure_class:'timeout',recovery_action:'retry',attempt:1}).valid,true);
assert.equal(c.checkRecoveryRecord({workflow_id:'wf1',failure_class:'timeout',recovery_action:'retry',attempt:0}).reason,'invalid_attempt');
console.log('Phase 8.14 assertions authored; runtime execution pending.');
